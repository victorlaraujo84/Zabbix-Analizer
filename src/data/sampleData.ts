export function getSampleZabbixEvents(): ZabbixEvent[] {
  return rawSampleRows.map((row, idx) => {
    const dataInicio = parseDate(row.hora);
    const dataFim = parseDate(row.horaRecup);
    const duracaoSegundos = row.duracaoISO ? parseDurationISO(row.duracaoISO) : 0;

    return {
      id: `sample-evt-${idx + 1}`,
      severidade: row.severidade,
      hora: row.hora,
      dataInicio,
      horaRecuperacao: row.horaRecup,
      dataFim,
      status: row.status,
      host: row.host,
      incidente: row.incidente,
      duracaoTexto: row.duracaoTexto || formatDuration(duracaoSegundos),
      duracaoSegundos,
      reconhecido: row.reconhecido,
      acoes: row.acoes,
      etiquetasTexto: row.etiquetas,
      etiquetas: parseTags(row.etiquetas),
      duracaoISO: row.duracaoISO,
    };
  });
}
